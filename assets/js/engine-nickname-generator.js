      const slider = document.getElementById("charRange");
      const rangeVal = document.getElementById("rangeVal");
      const mainBtn = document.getElementById("mainBtn");
      const toastEl = document.getElementById("copyToast");
      const toastMsg = document.getElementById("toastMsg");
      const bsToast = new bootstrap.Toast(toastEl, { delay: 2000 });

      slider.oninput = () => (rangeVal.innerText = slider.value);

      function showToast(msg, type = "success") {
        toastMsg.innerText = msg;
        toastEl.classList.remove("bg-success", "bg-warning", "bg-dark");
        if (type === "success") toastEl.classList.add("bg-success");
        else if (type === "warning")
          toastEl.classList.add("bg-dark", "text-white");
        else toastEl.classList.add("bg-dark");
        bsToast.show();
      }

      function copy(text) {
        if (navigator.clipboard && window.isSecureContext) {
          navigator.clipboard
            .writeText(text)
            .then(() => showToast("Nickname berhasil disalin!"))
            .catch(() => copyFallback(text));
        } else {
          copyFallback(text);
        }
      }

      function copyFallback(text) {
        const el = document.createElement("textarea");
        el.value = text;
        el.setAttribute("readonly", "");
        el.style.position = "absolute";
        el.style.left = "-9999px";
        document.body.appendChild(el);

        el.select();
        el.setSelectionRange(0, 9999);

        try {
          document.execCommand("copy");
          showToast("Nickname berhasil disalin!");
        } catch (err) {
          showToast("Gagal menyalin", "dark");
        }

        document.body.removeChild(el);
      }

      function buildName(cats, max) {
        let name = "";
        while (Array.from(name).length < max - 2) {
          let c = cats[Math.floor(Math.random() * cats.length)];
          let word = db[c][Math.floor(Math.random() * db[c].length)];
          name += word;
          if (Array.from(name).length >= max) break;
        }
        let finalArray = Array.from(name);
        return finalArray.length > max
          ? finalArray.slice(0, max).join("")
          : finalArray.join("");
      }

      function generateManual() {
        const selected = Array.from(
          document.querySelectorAll(".cat-check:checked"),
        ).map((c) => c.value);

        if (selected.length < 1) {
          showToast("Pilih minimal 1 kategori!", "warning");
          return;
        }
        if (selected.length > 3) {
          showToast("Pilih Maksimal 3 kategori!", "warning");
          return;
        }

        document.getElementById("copyInstruction").classList.remove("d-none");
        mainBtn.innerHTML = `<i class="bi bi-gear me-2"></i>Generate Lagi`;
        const container = document.getElementById("manualResult");
        container.innerHTML = `<div class="row g-2"><div class="col-6" id="L"></div><div class="col-6" id="R"></div></div>`;

        for (let i = 0; i < 20; i++) {
          let name = buildName(selected, parseInt(slider.value));
          let html = `<div class="nick-item d-flex justify-content-between align-items-center" onclick="copy('${name}')">
                        <span class="text-truncate">${name}</span>
                        <svg width="15" height="15" fill="none" stroke="currentColor" stroke-width="2" viewBox="0 0 24 24"><path d="M8 7v8a2 2 0 002 2h6M8 7V5a2 2 0 012-2h4.586a1 1 0 01.707.293l4.414 4.414a1 1 0 01.293.707V15a2 2 0 01-2 2h-2M8 7H6a2 2 0 00-2 2v10a2 2 0 002 2h8a2 2 0 002-2v-2"></path></svg>
                      </div>`;

          i < 10
            ? (document.getElementById("L").innerHTML += html)
            : (document.getElementById("R").innerHTML += html);
        }

        if (window.innerWidth < 992) {
          setTimeout(() => {
            container.scrollIntoView({ behavior: "smooth", block: "center" });
          }, 100);
        }
        initAuto();
      }

      function initAuto() {
        const container = document.getElementById("dynamicAuto");
        const allKeys = Object.keys(db).filter((k) => k !== "simbol");

        container.innerHTML = "";

        for (let i = 0; i < 12; i++) {
          let name = buildName(allKeys, 10);
          let symb = db.simbol[Math.floor(Math.random() * db.simbol.length)];
          let final = Math.random() > 0.5 ? symb + name : name + symb;
          let display = Array.from(final).slice(0, 12).join("");

          let col = document.createElement("div");
          col.className = "col-6 col-md-4 col-lg-3";
          col.innerHTML = `<div class="auto-card" onclick="copy('${display}')">${display}</div>`;
          container.appendChild(col);
        }
      }
      document.addEventListener("DOMContentLoaded", initAuto);